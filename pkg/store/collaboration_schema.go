// Additive registry owned by the canonical Go store, like its library/artifact
// tables. No workflow rows are renumbered and no provider instance is guessed.
const collaborationTeamsDDL = `CREATE TABLE collaboration_teams(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id>0), host TEXT NOT NULL REFERENCES collaboration_hosts(id), external_id TEXT NOT NULL CHECK(char_length(external_id) BETWEEN 1 AND 512), name TEXT NOT NULL, UNIQUE(host,external_id), UNIQUE(id,host))`

var collaborationDDL = []string{
	`CREATE TABLE collaboration_hosts(id TEXT PRIMARY KEY CHECK(id ~ '^[a-f0-9]{32}$'), provider TEXT NOT NULL CHECK(provider IN ('fountain','github')), api_base TEXT NOT NULL, UNIQUE(provider,api_base))`,
	`CREATE TABLE collaboration_profiles(id TEXT PRIMARY KEY CHECK(id ~ '^[a-f0-9]{32}$'), name TEXT NOT NULL)`,
	`CREATE TABLE collaboration_ledger(singleton BOOLEAN PRIMARY KEY CHECK(singleton), adopted BOOLEAN NOT NULL, fountain_host TEXT REFERENCES collaboration_hosts(id))`,
	`CREATE TABLE collaboration_repositories(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id>0), host TEXT NOT NULL REFERENCES collaboration_hosts(id), external_id TEXT NOT NULL CHECK(char_length(external_id) BETWEEN 1 AND 512), name TEXT NOT NULL, UNIQUE(host,external_id), UNIQUE(id,host))`,
	`CREATE TABLE collaboration_actors(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id>0), host TEXT NOT NULL REFERENCES collaboration_hosts(id), external_id TEXT NOT NULL CHECK(char_length(external_id) BETWEEN 1 AND 512), login TEXT NOT NULL, UNIQUE(host,external_id), UNIQUE(id,host))`,
	collaborationTeamsDDL,
	`CREATE TABLE collaboration_connections(id TEXT PRIMARY KEY CHECK(id ~ '^[a-f0-9]{32}$'), profile TEXT NOT NULL REFERENCES collaboration_profiles(id), host TEXT NOT NULL REFERENCES collaboration_hosts(id), actor BIGINT NOT NULL, FOREIGN KEY(actor,host) REFERENCES collaboration_actors(id,host), UNIQUE(id,host))`,
	`CREATE TABLE collaboration_repository_connections(repository BIGINT NOT NULL, connection TEXT NOT NULL, host TEXT NOT NULL, PRIMARY KEY(repository,connection), FOREIGN KEY(repository,host) REFERENCES collaboration_repositories(id,host), FOREIGN KEY(connection,host) REFERENCES collaboration_connections(id,host))`,
	`CREATE TABLE collaboration_runtimes(id TEXT PRIMARY KEY CHECK(id ~ '^[a-f0-9]{32}$'), profile TEXT NOT NULL REFERENCES collaboration_profiles(id), kind TEXT NOT NULL CHECK(kind IN ('native','appliance')), name TEXT NOT NULL)`,
	`CREATE FUNCTION soda_collaboration_identity() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE field TEXT;
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'collaboration identities retain history'; END IF;
 FOREACH field IN ARRAY TG_ARGV LOOP
  IF to_jsonb(NEW)->field IS DISTINCT FROM to_jsonb(OLD)->field THEN
   RAISE EXCEPTION 'collaboration identity cannot be rebound';
  END IF;
 END LOOP;
 RETURN NEW;
END $$`,
	`CREATE FUNCTION soda_collaboration_allocation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NOT COALESCE((SELECT adopted FROM collaboration_ledger WHERE singleton FOR SHARE),false) THEN
  RAISE EXCEPTION 'retained Fountain ledger is not adopted' USING ERRCODE='23514',CONSTRAINT='collaboration_ledger_unbound';
 END IF;
 RETURN NEW;
END $$`,
}

var collaborationIdentityFields = map[string]string{
	"hosts": "'id','provider'", "profiles": "'id'", "repositories": "'id','host','external_id'",
	"actors": "'id','host','external_id'", "connections": "'id','profile','host','actor'",
	"teams":    "'id','host','external_id'",
	"runtimes": "'id','profile','kind'",
}

func initializeCollaborationSchema(ctx context.Context, db *sql.DB) error {
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	// The existing schema marker serializes additive initialization across
	// processes, including a fresh profile opened by more than one component.
	var version int
	if err := tx.QueryRowContext(ctx, `SELECT version FROM schema_version FOR UPDATE`).Scan(&version); err != nil {
		return err
	}
	var present bool
	if err := tx.QueryRowContext(ctx, `SELECT to_regclass('public.collaboration_hosts') IS NOT NULL`).Scan(&present); err != nil {
		return err
	}
	if !present {
		for _, ddl := range collaborationDDL {
			if _, err := tx.ExecContext(ctx, ddl); err != nil {
				return fmt.Errorf("create collaboration registry: %w", err)
			}
		}
		// Opening a Store never selects the namespace for historic numbers.
		// Native composition explicitly initializes an empty ledger; retained
		// Fountain composition must use the adoption producer in T01-LEDGER.
		if _, err := tx.ExecContext(ctx, `INSERT INTO collaboration_ledger(singleton,adopted) VALUES(true,false)`); err != nil {
			return err
		}
		for table, fields := range collaborationIdentityFields {
			if _, err := tx.ExecContext(ctx, `CREATE TRIGGER collaboration_`+table+`_identity BEFORE UPDATE OR DELETE ON collaboration_`+table+` FOR EACH ROW EXECUTE FUNCTION soda_collaboration_identity(`+fields+`)`); err != nil {
				return err
			}
		}
		for _, table := range []string{"repositories", "actors", "teams"} {
			if _, err := tx.ExecContext(ctx, `CREATE TRIGGER collaboration_`+table+`_allocation BEFORE INSERT ON collaboration_`+table+` FOR EACH ROW EXECUTE FUNCTION soda_collaboration_allocation()`); err != nil {
				return err
			}
		}
	}
	// Existing registries predate canonical teams. Add this identity space under
	// the same schema-marker lock without changing existing IDs or core workflow
	// format. An existing but incomplete/unguarded table must fail verification.
	if present {
		var teams bool
		if err := tx.QueryRowContext(ctx, `SELECT to_regclass('public.collaboration_teams') IS NOT NULL`).Scan(&teams); err != nil {
			return err
		}
		if !teams {
			for _, ddl := range []string{
				collaborationTeamsDDL,
				`CREATE TRIGGER collaboration_teams_identity BEFORE UPDATE OR DELETE ON collaboration_teams FOR EACH ROW EXECUTE FUNCTION soda_collaboration_identity('id','host','external_id')`,
				`CREATE TRIGGER collaboration_teams_allocation BEFORE INSERT ON collaboration_teams FOR EACH ROW EXECUTE FUNCTION soda_collaboration_allocation()`,
			} {
				if _, err := tx.ExecContext(ctx, ddl); err != nil {
					return fmt.Errorf("add collaboration team registry: %w", err)
				}
			}
		}
	}
	if err := verifyCollaborationSchema(ctx, tx); err != nil {
		return err
	}
	return tx.Commit()
}

func emptyCollaborationLedger(ctx context.Context, tx *sql.Tx) (bool, error) {
	// The readiness budget is a seeded global scheduler counter, with no remote
	// repository/actor identity. Its initial row is present even in an empty DB.
	rows, err := tx.QueryContext(ctx, `SELECT tablename FROM pg_tables WHERE schemaname='public' AND tablename NOT IN ('schema_version','factory_readiness_budget') AND left(tablename,14)<>'collaboration_' ORDER BY tablename`)
	if err != nil {
		return false, err
	}
	var tables []string
	for rows.Next() {
		var name string
		if err := rows.Scan(&name); err != nil {
			rows.Close()
			return false, err
		}
		tables = append(tables, name)
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return false, err
	}
	for _, table := range tables {
		// An old writer may have begun before composition took the ledger gate.
		// Wait for it before testing emptiness, then keep writes excluded until
		// the binding commits. The lock order is stable across initializers.
		if _, err := tx.ExecContext(ctx, `LOCK TABLE public.`+quoteCollaborationIdentifier(table)+` IN SHARE MODE`); err != nil {
			return false, err
		}
	}
	for _, table := range tables {
		var present bool
		if err := tx.QueryRowContext(ctx, `SELECT EXISTS(SELECT 1 FROM public."`+strings.ReplaceAll(table, `"`, `""`)+`" LIMIT 1)`).Scan(&present); err != nil {
			return false, err
		}
		if present {
			return false, nil
		}
	}
	return true, nil
}

func verifyCollaborationSchema(ctx context.Context, tx *sql.Tx) error {
	for _, query := range []string{
		`SELECT id,provider,api_base FROM collaboration_hosts LIMIT 0`, `SELECT id,name FROM collaboration_profiles LIMIT 0`,
		`SELECT id,host,external_id,name FROM collaboration_repositories LIMIT 0`, `SELECT id,host,external_id,login FROM collaboration_actors LIMIT 0`,
		`SELECT id,host,external_id,name FROM collaboration_teams LIMIT 0`,
		`SELECT id,profile,host,actor FROM collaboration_connections LIMIT 0`, `SELECT repository,connection,host FROM collaboration_repository_connections LIMIT 0`,
		`SELECT id,profile,kind,name FROM collaboration_runtimes LIMIT 0`,
	} {
		rows, err := tx.QueryContext(ctx, query)
		if err != nil {
			return errors.New("collaboration registry is incomplete")
		}
		if err = rows.Close(); err != nil {
			return err
		}
	}
	var adopted bool
	var host sql.NullString
	if err := tx.QueryRowContext(ctx, `SELECT adopted,fountain_host FROM collaboration_ledger WHERE singleton`).Scan(&adopted, &host); err != nil {
		return errors.New("collaboration ledger binding is absent")
	}
	for table := range collaborationIdentityFields {
		if err := verifyCollaborationTrigger(ctx, tx, "collaboration_"+table+"_identity", "collaboration_"+table, "soda_collaboration_identity", 27); err != nil {
			return err
		}
	}
	for _, table := range []string{"repositories", "actors", "teams"} {
		if err := verifyCollaborationTrigger(ctx, tx, "collaboration_"+table+"_allocation", "collaboration_"+table, "soda_collaboration_allocation", 7); err != nil {
			return err
		}
	}
	return nil
}

// pg_trigger has one row per trigger; information_schema.triggers has one row
// per event and therefore counts an UPDATE OR DELETE guard twice.
func verifyCollaborationTrigger(ctx context.Context, tx *sql.Tx, name, table, function string, events int) error {
	var count int
	if err := tx.QueryRowContext(ctx, `SELECT count(*) FROM pg_trigger t
 JOIN pg_class c ON c.oid=t.tgrelid JOIN pg_namespace n ON n.oid=c.relnamespace
 JOIN pg_proc p ON p.oid=t.tgfoid
 WHERE n.nspname='public' AND c.relname=$1 AND t.tgname=$2 AND p.proname=$3
 AND t.tgtype=$4 AND t.tgenabled IN ('O','A') AND NOT t.tgisinternal`, table, name, function, events).Scan(&count); err != nil {
		return err
	}
	if count != 1 {
		return errors.New("collaboration registry guard is absent or disabled")
	}
	return nil
}
